#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const ENFORCE = process.argv.includes('--enforce');

const COPY_MARKERS = [
  /copied from/i,
  /copied\s+from\s+https?:\/\//i,
  /all rights reserved/i,
  /do not distribute/i,
  /proprietary code/i,
];

const FORBIDDEN_LICENSE_PATTERNS = [
  /\bGPL-\d/i,
  /\bAGPL-\d/i,
];

const RISKY_ASSETS = [
  'public/vercel.svg',
  'public/next.svg',
];

const TARGET_EXTENSIONS = new Set(['.js', '.ts', '.tsx', '.mjs', '.json', '.md', '.txt', '.yml', '.yaml']);

function exists(relPath) {
  return fs.existsSync(path.join(ROOT, relPath));
}

function walk(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === 'node_modules' || entry.name === '.git' || entry.name === 'dist' || entry.name === 'ios') continue;
      walk(full, out);
      continue;
    }
    const ext = path.extname(entry.name).toLowerCase();
    if (TARGET_EXTENSIONS.has(ext)) out.push(full);
  }
  return out;
}

function readJSON(filePath, fallback = null) {
  try {
    return JSON.parse(fs.readFileSync(filePath, 'utf8'));
  } catch {
    return fallback;
  }
}

function collectLockfileLicenses() {
  const lockPath = path.join(ROOT, 'package-lock.json');
  const lock = readJSON(lockPath, {});
  const packages = lock && lock.packages ? lock.packages : {};
  const rows = [];

  for (const [key, meta] of Object.entries(packages)) {
    if (!key || !key.startsWith('node_modules/')) continue;
    if (!meta || typeof meta !== 'object') continue;
    const name = key.replace(/^node_modules\//, '');
    const license = String(meta.license || 'UNKNOWN');
    rows.push({ name, version: String(meta.version || ''), license });
  }

  rows.sort((a, b) => a.name.localeCompare(b.name));
  return rows;
}

function findCopyMarkers() {
  const files = [
    ...walk(path.join(ROOT, 'app')),
    ...walk(path.join(ROOT, 'lib')),
    ...walk(path.join(ROOT, 'scripts')),
    ...walk(path.join(ROOT, 'docs')),
    ...walk(path.join(ROOT, 'marketing-kit')),
    ...walk(ROOT).filter((f) => /README|LICENSE|MARKETING-KIT|WELCOME/.test(path.basename(f))),
  ];

  const findings = [];
  for (const file of files) {
    const rel = path.relative(ROOT, file);
    if (rel === 'scripts/copyright-compliance-audit.js') continue;

    let text = '';
    try {
      text = fs.readFileSync(file, 'utf8');
    } catch {
      continue;
    }

    for (const pattern of COPY_MARKERS) {
      if (pattern.test(text)) {
        findings.push({ file: rel, marker: String(pattern) });
      }
    }
  }
  return findings;
}

function writeThirdPartySummary(licenses) {
  const byLicense = new Map();
  for (const dep of licenses) {
    const key = dep.license;
    const row = byLicense.get(key) || { license: key, count: 0 };
    row.count += 1;
    byLicense.set(key, row);
  }

  const sorted = [...byLicense.values()].sort((a, b) => a.license.localeCompare(b.license));

  const lines = [];
  lines.push('# Third-Party License Summary');
  lines.push('');
  lines.push('Generated by `npm run copyright:audit` from `package-lock.json`.');
  lines.push('');
  lines.push('| License | Package Count |');
  lines.push('|---|---:|');
  for (const row of sorted) {
    lines.push(`| ${row.license} | ${row.count} |`);
  }
  lines.push('');
  lines.push('## Notes');
  lines.push('');
  lines.push('- Keep this summary updated whenever dependencies change.');
  lines.push('- Run legal review if a forbidden license (GPL/AGPL) appears.');
  lines.push('');

  const outPath = path.join(ROOT, 'docs', 'THIRD_PARTY_LICENSES.md');
  fs.writeFileSync(outPath, `${lines.join('\n')}\n`, 'utf8');
}

function main() {
  const hasLicenseFile = exists('LICENSE');
  const riskyAssetsFound = RISKY_ASSETS.filter((relPath) => exists(relPath));
  const markerFindings = findCopyMarkers();
  const dependencyLicenses = collectLockfileLicenses();

  const unknownLicenses = dependencyLicenses.filter((dep) => /UNKNOWN|UNLICENSED/i.test(dep.license));
  const forbiddenLicenses = dependencyLicenses.filter((dep) => FORBIDDEN_LICENSE_PATTERNS.some((pat) => pat.test(dep.license)));

  writeThirdPartySummary(dependencyLicenses);

  const report = {
    timestamp: new Date().toISOString(),
    hasLicenseFile,
    riskyAssetsFound,
    markerFindings,
    dependencyCount: dependencyLicenses.length,
    unknownLicenseCount: unknownLicenses.length,
    forbiddenLicenseCount: forbiddenLicenses.length,
    unknownLicenses: unknownLicenses.slice(0, 50),
    forbiddenLicenses: forbiddenLicenses.slice(0, 50),
    status: 'pass',
  };

  const failures = [];
  if (!hasLicenseFile) failures.push('Missing LICENSE file');
  if (riskyAssetsFound.length > 0) failures.push(`Risky third-party assets found: ${riskyAssetsFound.join(', ')}`);
  if (unknownLicenses.length > 0) failures.push(`Dependencies with unknown licenses: ${unknownLicenses.length}`);
  if (forbiddenLicenses.length > 0) failures.push(`Dependencies with forbidden licenses (GPL/AGPL): ${forbiddenLicenses.length}`);
  if (markerFindings.length > 0) failures.push(`Potential copied-content markers found: ${markerFindings.length}`);

  if (failures.length > 0) {
    report.status = 'fail';
    report.failures = failures;
  }

  const reportDir = path.join(ROOT, 'dist');
  fs.mkdirSync(reportDir, { recursive: true });
  const reportPath = path.join(reportDir, 'copyright-audit-report.json');
  fs.writeFileSync(reportPath, `${JSON.stringify(report, null, 2)}\n`, 'utf8');

  console.log(`Copyright audit status: ${report.status}`);
  console.log(`LICENSE present: ${hasLicenseFile}`);
  console.log(`Dependency entries audited: ${dependencyLicenses.length}`);
  console.log(`Unknown dependency licenses: ${unknownLicenses.length}`);
  console.log(`Forbidden dependency licenses: ${forbiddenLicenses.length}`);
  console.log(`Copy marker findings: ${markerFindings.length}`);
  console.log(`Risky assets found: ${riskyAssetsFound.length}`);
  console.log(`Third-party summary: docs/THIRD_PARTY_LICENSES.md`);
  console.log(`Audit report: ${path.relative(ROOT, reportPath)}`);

  if (markerFindings.length > 0) {
    console.log('Potential copy-marker findings:');
    for (const finding of markerFindings.slice(0, 20)) {
      console.log(`- ${finding.file} matched ${finding.marker}`);
    }
  }

  if (ENFORCE && report.status !== 'pass') {
    process.exit(1);
  }
}

main();
